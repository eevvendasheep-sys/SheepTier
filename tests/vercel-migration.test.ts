import assert from 'node:assert/strict';
import {isSameSiteRequest} from '../lib/request-origin';
import {clientIP} from '../lib/client-ip';
import {initialDocument} from '../lib/store';
import {publicLeaderboard} from '../lib/public-leaderboard';
process.env.VERCEL='1';process.env.VERCEL_URL='sheeptier-deploy.vercel.app';process.env.VERCEL_PROJECT_PRODUCTION_URL='sheeptier-prod.vercel.app';
const req=(origin:string,extra:Record<string,string>={})=>new Request('https://internal.example/api/account',{headers:{origin,...extra}});
assert.ok(isSameSiteRequest(req('https://sheeptier-prod.vercel.app')));
assert.ok(isSameSiteRequest(req('https://sheeptier-deploy.vercel.app')));
assert.ok(!isSameSiteRequest(req('https://other.vercel.app')));
assert.ok(!isSameSiteRequest(req('https://sheeptier-prod.vercel.app',{'sec-fetch-site':'cross-site'})));
assert.equal(clientIP(req('https://site.test',{'x-vercel-forwarded-for':'203.0.113.2','x-nf-client-connection-ip':'198.51.100.1'})),'203.0.113.2');
assert.equal(clientIP(req('https://site.test',{'x-vercel-forwarded-for':'2001:db8::1'})),'2001:db8::1');
assert.equal(clientIP(req('https://site.test',{'x-vercel-forwarded-for':'not-an-ip'})),null);
delete process.env.VERCEL;
assert.equal(clientIP(req('https://site.test',{'x-forwarded-for':'203.0.113.2'})),null);
const doc=initialDocument();doc.discord_rank={guild_id:'secret',token_hash:'secret',recent:[]};doc.admin_player_id='private';doc.users=[{id:'private',email:'private',display_name:'private',role:'admin'}];
const output=publicLeaderboard(doc);
assert.deepEqual(Object.keys(output).sort(),['settings','modes','tiers','players','rankings'].sort());
assert.ok(!JSON.stringify(output).includes('secret'));assert.ok(!JSON.stringify(output).includes('private'));
console.log('OK : origines Vercel, IP de confiance, classement sans clés ni comptes privés.');
