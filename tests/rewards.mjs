import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const compile = source => ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const rewardUrl = 'data:text/javascript;base64,'+Buffer.from(compile(await readFile('lib/sheep-rewards.ts','utf8'))).toString('base64');
const rewards = await import(rewardUrl);
const {parseRewards, mergeRewards, unlockedSkins, recordReward, importGameRewards, getRewards} = rewards;
assert.deepEqual(parseRewards({runner:NaN,wheat:Infinity,memory:7}),{runner:0,wheat:0,memory:0});
assert.equal(parseRewards({memory:8.5}).memory,0);
assert.deepEqual(unlockedSkins(parseRewards({runner:99,wheat:99})),['classic']);
assert.deepEqual(unlockedSkins(parseRewards({runner:100,wheat:100,memory:13})),['classic','hero','farmer','flower']);
assert.equal(unlockedSkins(parseRewards({runner:299,wheat:9999,memory:13})).includes('rainbow'),false);
assert.equal(unlockedSkins(parseRewards({memory:12})).includes('rainbow'),true);
assert.equal(unlockedSkins(parseRewards({memory:8})).includes('rainbow'),true);
assert.equal(unlockedSkins(parseRewards({runner:300,wheat:10000,memory:12})).length,7);
assert.deepEqual(mergeRewards({runner:300,wheat:10000,memory:12},{runner:1,wheat:0,memory:20}),{runner:300,wheat:10000,memory:12});
const storage = new Map();
globalThis.localStorage = {getItem:key=>storage.get(key)??null,setItem:(key,value)=>storage.set(key,value)};
const events=[];
globalThis.CustomEvent = class {constructor(type,options){this.type=type;this.detail=options.detail;}};
globalThis.window={dispatchEvent:event=>events.push(event)};
storage.set('sheeptier-run-best','300');
storage.set('sheeptier-wheat-farm',JSON.stringify({farm:{total:10000}}));
storage.set('sheeptier-memory-best','12');
assert.equal(unlockedSkins(importGameRewards()).length,7);
assert.ok(events.every(event=>event.detail.newlyUnlocked.length===0));
storage.set('sheeptier-wheat-farm',JSON.stringify({farm:{total:0}}));
recordReward('wheat',0);
assert.equal(getRewards().wheat,10000);
const reload=await import(rewardUrl+'#reload');
assert.equal(unlockedSkins(reload.getRewards()).length,7);
storage.clear();
const fresh=await import(rewardUrl+'#fresh');
events.length=0;
fresh.recordReward('runner',100);
assert.deepEqual(events[0].detail.newlyUnlocked,['hero']);
fresh.recordReward('runner',100);
assert.equal(events.length,1);
fresh.recordReward('memory',8);
assert.deepEqual(events[1].detail.newlyUnlocked,['flower','rainbow']);
const appearanceCode=compile(await readFile('lib/appearance.ts','utf8')).replace('"./sheep-rewards"',JSON.stringify(rewardUrl));
const {parseAppearance,defaultAppearance}=await import('data:text/javascript;base64,'+Buffer.from(appearanceCode).toString('base64'));
assert.deepEqual(parseAppearance({skin:'unknown'}),defaultAppearance);
assert.equal(parseAppearance({skin:'royal'}).skin,'royal');
assert.equal(parseAppearance({theme:'spring',wool:'#AABBCC',animated:false}).skin,'classic');
console.log('Verified: six reward thresholds, invalid saves, retroactive unlocks, durable rewards after reset/reload, one-time notifications and appearance migration.');
